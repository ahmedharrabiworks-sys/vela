// npm run sales:autostart [install|remove|status]
// Registers the "Vela sales" task for the current user only (no admin rights): at login it waits
// 30 s for the network, then runs sales/worker/launch.mjs, and repeats every 5 minutes, so a
// closed window comes back within 5 minutes. The launcher runs hidden through wscript (no
// flashing console); the worker itself opens in a minimized "Vela sales" window.
// If Task Scheduler refuses, it falls back to a Startup folder shortcut (login only, no repeat).
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { ROOT, TASK_NAME } from "./proc.mjs";

const action = process.argv[2] || "install";
const DIR = path.join(ROOT, "sales", "data", "autostart"); // gitignored: holds local paths
const VBS = path.join(DIR, "launch.vbs");
const STARTUP = path.join(process.env.APPDATA || "", "Microsoft", "Windows", "Start Menu", "Programs", "Startup", "Vela sales.vbs");
const run = (cmd, args) => execFileSync(cmd, args, { encoding: "utf8", windowsHide: true, stdio: ["ignore", "pipe", "pipe"] });
const xmlEsc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

function query() { try { return run("schtasks", ["/Query", "/TN", TASK_NAME, "/V", "/FO", "LIST"]); } catch { return null; } }

if (action === "status") {
  const q = query();
  if (q) console.log(q.split(/\r?\n/).filter((l) => /^(TaskName|Status|Next Run Time|Last Run Time|Last Result|Logon Mode|Repeat: Every):/.test(l)).join("\n"));
  else console.log(fs.existsSync(STARTUP) ? "Startup folder shortcut installed (login only)." : "Not installed. Run: npm run sales:autostart");
  process.exit(0);
}
if (action === "remove") {
  try { run("schtasks", ["/Delete", "/TN", TASK_NAME, "/F"]); console.log("Scheduled task removed."); } catch { console.log("No scheduled task."); }
  fs.rmSync(STARTUP, { force: true });
  process.exit(0);
}

fs.mkdirSync(DIR, { recursive: true });
// wscript runs node with window style 0 (hidden): nothing flashes every 5 minutes.
fs.writeFileSync(VBS, `' Vela sales autostart (generated by npm run sales:autostart)\r\nSet sh = CreateObject("WScript.Shell")\r\nsh.CurrentDirectory = "${ROOT}"\r\nsh.Run """${process.execPath}"" ""${path.join(ROOT, "sales", "worker", "launch.mjs")}""", 0, False\r\n`);
const user = run("whoami", []).trim();
const xml = `<?xml version="1.0" encoding="UTF-16"?>
<Task version="1.2" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo><Description>Starts the Vela sales laptop worker at login and brings it back within 5 minutes if its window is closed.</Description></RegistrationInfo>
  <Triggers>
    <LogonTrigger>
      <Enabled>true</Enabled>
      <UserId>${xmlEsc(user)}</UserId>
      <Delay>PT30S</Delay>
      <Repetition><Interval>PT5M</Interval><StopAtDurationEnd>false</StopAtDurationEnd></Repetition>
    </LogonTrigger>
  </Triggers>
  <Principals><Principal id="Author"><UserId>${xmlEsc(user)}</UserId><LogonType>InteractiveToken</LogonType><RunLevel>LeastPrivilege</RunLevel></Principal></Principals>
  <Settings>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <DisallowStartIfOnBatteries>false</DisallowStartIfOnBatteries>
    <StopIfGoingOnBatteries>false</StopIfGoingOnBatteries>
    <StartWhenAvailable>true</StartWhenAvailable>
    <RunOnlyIfNetworkAvailable>false</RunOnlyIfNetworkAvailable>
    <IdleSettings><StopOnIdleEnd>false</StopOnIdleEnd><RestartOnIdle>false</RestartOnIdle></IdleSettings>
    <AllowStartOnDemand>true</AllowStartOnDemand>
    <Enabled>true</Enabled>
    <Hidden>false</Hidden>
    <ExecutionTimeLimit>PT5M</ExecutionTimeLimit>
  </Settings>
  <Actions Context="Author"><Exec><Command>wscript.exe</Command><Arguments>//B //Nologo "${xmlEsc(VBS)}"</Arguments><WorkingDirectory>${xmlEsc(ROOT)}</WorkingDirectory></Exec></Actions>
</Task>`;
const xmlFile = path.join(os.tmpdir(), "vela-sales-task.xml");
fs.writeFileSync(xmlFile, "﻿" + xml, "utf16le");
try {
  run("schtasks", ["/Create", "/TN", TASK_NAME, "/XML", xmlFile, "/F"]);
  fs.rmSync(STARTUP, { force: true });
  console.log(`Installed the "${TASK_NAME}" scheduled task for ${user}: at login (+30 s), then every 5 minutes. No admin rights used.`);
} catch (e) {
  fs.copyFileSync(VBS, STARTUP);
  console.log(`Task Scheduler refused (${String(e.stderr || e.message).trim()}). Installed a Startup folder shortcut instead (login only, no 5 minute repeat).`);
} finally { fs.rmSync(xmlFile, { force: true }); }
